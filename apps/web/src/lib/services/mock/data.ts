export function paginate<T>(items: readonly T[], params?: { readonly page?: number; readonly pageSize?: number; readonly query?: string; readonly totalOverride?: number }) {
  const page = Math.max(1, params?.page ?? 1);
  const pageSize = params?.pageSize ?? 20;
  const filtered = params?.query
    ? items.filter((i) => JSON.stringify(i).toLowerCase().includes(params.query!.toLowerCase()))
    : items;
  const total = params?.totalOverride ?? filtered.length;
  const start = (page - 1) * pageSize;
  return {
    items: filtered.slice(start, start + pageSize),
    total,
    page,
    pageSize,
  };
}
